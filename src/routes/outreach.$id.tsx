import { createFileRoute } from "@tanstack/react-router";
import { createServerFn } from "@tanstack/react-start";
import { createClient } from "@supabase/supabase-js";
import { format } from "date-fns";

// Server function to fetch sequence by ID
const fetchSequenceFn = createServerFn({ method: "GET" })
  .validator((input: unknown) => ({ id: (input as any)?.id as string }))
  .handler(async ({ data }) => {
    const supabase = createClient(
      process.env.VITE_SUPABASE_URL ?? import.meta.env.VITE_SUPABASE_URL,
      process.env.VITE_SUPABASE_PUBLISHABLE_KEY ?? import.meta.env.VITE_SUPABASE_PUBLISHABLE_KEY
    );
    const { data: seq, error } = await supabase
      .from("bde_sequences")
      .select("*")
      .eq("id", data.id)
      .single();
    if (error || !seq) return null;
    return seq as {
      id: string;
      created_at: string;
      generated_by: string;
      generated_by_email: string;
      client_name: string;
      linkedin_post: string;
      full_sequence: string;
    };
  });

export const Route = createFileRoute("/outreach/$id")({
  loader: async ({ params }) => {
    const seq = await fetchSequenceFn({ data: { id: params.id } });
    return { seq };
  },
  component: OutreachPage,
});

